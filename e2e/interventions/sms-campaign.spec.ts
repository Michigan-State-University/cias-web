/**
 * Stubs the participant list. The path has to be matched exactly: the campaign
 * endpoints live UNDER `/predefined_participants`, so a substring match would
 * swallow them too.
 */
const stubParticipants = async (page: any, pages: unknown[][]) => {
  let call = 0;
  await page.route(
    (url: URL) => url.pathname.endsWith('/predefined_participants'),
    async (route: any) => {
      if (route.request().method() !== 'GET') return route.fallback();
      const data = pages[Math.min(call, pages.length - 1)];
      call += 1;
      return route.fulfill({
        status: 200,
        contentType: 'application/json',
        body: JSON.stringify({ data }),
      });
    },
  );
};

