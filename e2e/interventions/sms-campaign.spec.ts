  test('counts characters including the personal link and flips to UCS-2', async ({
    page,
  }) => {
    await stubMeta(page);
    await stubCampaignList(page, []);

    const inviter = await setUpPublishedInterventionWithParticipant(page);
    await inviter.openCampaignsView();
    await inviter.openCompose('invitation');

    // 'Hello' (5) + newline + the 34-character personal link the backend adds.
    await inviter.bodyInput.fill('Hello');
    expect(await inviter.readCounter()).toEqual({
      length: 40,
      segments: 1,
      encoding: 'GSM7',
    });

    // A character outside the GSM-7 alphabet halves the per-segment budget.
    await inviter.bodyInput.fill('Zażółć');
    const ucs2 = await inviter.readCounter();
    expect(ucs2.encoding).toEqual('UCS2');
    expect(ucs2.length).toEqual(41);

    // Exactly one GSM-7 segment at 160 units, two at 161.
    await inviter.bodyInput.fill('a'.repeat(125));
    expect(await inviter.readCounter()).toMatchObject({
      length: 160,
      segments: 1,
    });
    await inviter.bodyInput.fill('a'.repeat(126));
    expect(await inviter.readCounter()).toMatchObject({
      length: 161,
      segments: 2,
    });
  });

