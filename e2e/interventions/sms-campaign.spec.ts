/**
 * The participant list renders timestamps through `formatTimestamp` in
 * `ParticipantInviter/utils.ts`, i.e. dayjs' localized `L LT` (`11/01/2026
 * 10:30 AM` in the `en` locale). Build the expectation the same way instead of
 * hard-coding a string, so the assertion holds in any locale or timezone the
 * suite happens to run in.
 */
const renderedTimestamp = (iso: string) => dayjs(iso).format('L LT');

/**
 * That cell is an `EllipsisText`, which truncates in the DOM itself — the text
 * node is cut to the column width (`11/01/2026 1…`), so the full timestamp is
 * never in `textContent` and `toContainText` cannot see it. The untruncated
 * value is kept in `data-tip` (the tooltip source), which is what this asserts
 * on.
 */
const expectReminderTimestamp = async (
  row: Locator,
  iso: string,
  timeout?: number,
) =>
  expect(row.locator(`[data-tip="${renderedTimestamp(iso)}"]`)).toBeVisible(
    timeout ? { timeout } : undefined,
  );

/**
 * Custom SMS invitations for predefined participants.
 *
 * The backend throttles hard — 1 open campaign of a kind per intervention,
 * 5 creates/hour per intervention, 10/min per IP, and a 60 min resend cooldown
 * per participant. Every test therefore creates its own intervention, and only
 * ONE test posts a campaign for real; that one targets a participant with no
 * phone number, so the API answers NO_RECIPIENTS and no SMS is ever sent.
 * The rest stub the campaign endpoints with `page.route`.
 */

const SMS_CAMPAIGNS_URL = /\/sms_campaigns(\?|$)/;
const META_URL = /\/sms_campaigns\/meta/;

const META_BODY = {
  personal_link_template: 'http://localhost:4200/usr/:slug',
  personal_link_expected_length: 34,
  tracked_link_template: 'http://localhost:4200/link/:slug',
  tracked_link_expected_length: 36,
  gsm7_segment_lengths: [160, 153],
  ucs2_segment_lengths: [70, 67],
  max_body_length: 1600,
  max_segments: 24,
  max_reminder_days_after: 30,
};

const campaign = (overrides: Record<string, unknown> = {}) => ({
  id: String(overrides.id ?? 'campaign-1'),
  type: 'sms_campaign',
  attributes: {
    kind: 'invitation',
    status: 'sent',
    scheduled_at: '2026-10-30T12:00:00.000Z',
    sent_at: '2026-10-30T12:00:00.000Z',
    accepted_count: 1,
    failed_count: 0,
    recipients_count: 1,
    scheduled_at_provisional: false,
    ...overrides,
  },
});

const stubMeta = async (page: any) => {
  await page.route(META_URL, (route: any) =>
    route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify(META_BODY),
    }),
  );
};

const stubCampaignList = async (page: any, data: unknown[]) => {
  await page.route(SMS_CAMPAIGNS_URL, async (route: any) => {
    if (route.request().method() !== 'GET') return route.fallback();
    return route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify({ data }),
    });
  });
};

/** Creates a published intervention with one predefined participant. */
const setUpPublishedInterventionWithParticipant = async (page: any) => {
  const dashboardPage = new DashboardPage(page);
  const interventionPage = new InterventionPage(page);
  const inviter = new ParticipantInviterPage(page);

  await dashboardPage.goto();
  await dashboardPage.createIntervention();
  await interventionPage.createSession();
  await interventionPage.publishIntervention();

  await inviter.open();
  await inviter.goToPredefinedParticipantsTab();
  await inviter.createPredefinedParticipant(`e2e-${Date.now()}`);

  return inviter;
};

