export enum ParticipantUploadErrorCode {
  FILE_TYPE_NOT_ALLOWED = 'FILE_TYPE_NOT_ALLOWED',
  FILE_TOO_LARGE = 'FILE_TOO_LARGE',
  TOO_MANY_FILES = 'TOO_MANY_FILES',
  FILE_MISSING = 'FILE_MISSING',
  SESSION_FINISHED = 'SESSION_FINISHED',
  FILE_PENDING_SCAN = 'FILE_PENDING_SCAN',
  FILE_REMOVED_BY_SECURITY_SCAN = 'FILE_REMOVED_BY_SECURITY_SCAN',
}

export const UPLOAD_FAILED = 'UPLOAD_FAILED';

export type ParticipantUploadFailure =
  | ParticipantUploadErrorCode
  | typeof UPLOAD_FAILED;
